def read_combined_theory_flags(combined_dir):
    """Returns (spin_polarized, dipole_corrected, vdw_corrected) read from
    the combined system's own config_extra.fdf under `combined_dir`, or
    (False, False, False) if it has none -- same "duplicated per workflow,
    read the sidecar rather than re-deriving from CLI flags" convention as
    adsorb_bsse.py's read_site_theory_flags/her_refs.py/oer_refs.py.
    """
    path = os.path.join(combined_dir, CONFIG_EXTRA_FILE)
    if not os.path.isfile(path):
        return False, False, False
    with open(path) as f:
        text = f.read()
    return "Spin" in text, "Slab.DipoleCorrection" in text, "DFTD3" in text


def label_fragments_n(structure, groups, suffixes):
    """Generalizes core/adsorption_sites.py::label_fragments from a single
    2-way index cut to an arbitrary list of `groups` (each a list of atom
    indices into structure.atoms, in file order -- contiguous for a
    --fragment-sizes split, arbitrary for a --fragment-species split).
    Every atom gets its label suffixed by `suffixes[i]` for whichever
    group it belongs to. Kept local to this tool (not core/) since it's
    the sole consumer today of an N-way split -- extract-on-second-use,
    same policy as the rest of the project (compare her_refs.py's own
    local index-range make_ghost_variant).
    """
    label_for_index = {}
    for group, suffix in zip(groups, suffixes):
        for i in group:
            label_for_index[i] = suffix

    species_meta = dict(structure.species_meta)
    new_atoms = []
    for i, (symbol, pos) in enumerate(structure.atoms):
        label = f"{symbol}{label_for_index[i]}"
        if label not in species_meta:
            used_ids = {str(info["id"]) for info in species_meta.values()}
            next_id = 1
            while str(next_id) in used_ids:
                next_id += 1
            species_meta[label] = {"id": str(next_id), "Z": species_meta[symbol]["Z"]}
        new_atoms.append((label, pos))

    species = list(dict.fromkeys(sym for sym, _ in new_atoms))
    return structure_io.FdfStructure(
        lattice=structure.lattice,
        lattice_constant=structure.lattice_constant,
        species=species,
        species_meta=species_meta,
        atoms=new_atoms,
        coord_format=structure.coord_format,
        raw_lines=[],
    )


def parse_fragment_sizes(spec, n_atoms_total):
    """Parses '--fragment-sizes "n1,n2,...,nK"' into a list of K index
    groups, contiguous in file order (group 0 = first n1 atoms, group 1 =
    next n2, ...). Raises ValueError with a human-readable reason on a
    malformed spec, fewer than 2 groups, a non-positive size, or a sum
    that doesn't exactly match the structure's own atom count -- no
    guessing, matching this suite's general error-handling convention.
    """
    try:
        sizes = [int(x) for x in spec.split(",")]
    except ValueError:
        raise ValueError(f"--fragment-sizes must be a comma-separated list of integers, got: {spec!r}")
    if len(sizes) < 2:
        raise ValueError("--fragment-sizes needs at least 2 fragments (K >= 2), separated by commas.")
    if any(size <= 0 for size in sizes):
        raise ValueError("--fragment-sizes: every fragment size must be a positive integer.")
    if sum(sizes) != n_atoms_total:
        raise ValueError(
            f"--fragment-sizes sums to {sum(sizes)} atom(s) but the combined structure has "
            f"{n_atoms_total} -- the sizes must add up exactly (no atom left over/missing)."
        )
    groups = []
    start = 0
    for size in sizes:
        groups.append(list(range(start, start + size)))
        start += size
    return groups


def parse_fragment_species(spec, structure):
    """Parses '--fragment-species "El_a,El_b;El_c;..."' (';'-separated
    groups, ','-separated element symbols within a group) into a list of
    index groups, by REAL element (structure_io.real_element, robust to
    any label suffix already on the combined structure) rather than atom
    order -- works regardless of where each fragment's atoms sit in the
    file, unlike --fragment-sizes. Raises ValueError if fewer than 2
    groups are given, a species is assigned to more than one group, a
    species present in the structure is missing from every group, or a
    named species isn't present in the structure at all -- this mode
    cannot disambiguate two fragments sharing an element (see this tool's
    --help for the documented limitation), so an unambiguous full
    assignment is required, never guessed.
    """
    groups_species = [
        [sym.strip() for sym in group.split(",") if sym.strip()]
        for group in spec.split(";")
    ]
    groups_species = [g for g in groups_species if g]
    if len(groups_species) < 2:
        raise ValueError("--fragment-species needs at least 2 fragments (groups separated by ';').")

    real_symbol_by_index = [
        structure_io.real_element(symbol, structure.species_meta) for symbol, _ in structure.atoms
    ]
    present_species = set(real_symbol_by_index)

    seen = set()
    for group_species in groups_species:
        for sp in group_species:
            if sp in seen:
                raise ValueError(f"--fragment-species: species '{sp}' appears in more than one group.")
            seen.add(sp)

    unknown = seen - present_species
    if unknown:
        raise ValueError(
            f"--fragment-species: species not present in the combined structure: "
            f"{', '.join(sorted(unknown))}."
        )
    missing = present_species - seen
    if missing:
        raise ValueError(
            f"--fragment-species: the combined structure has species not assigned to any "
            f"fragment: {', '.join(sorted(missing))}. Every species must be assigned to exactly "
            "one group -- if two fragments physically share a species, use --fragment-sizes or "
            "--fragment-manifest instead (see --help)."
        )

    groups = [
        [i for i, sym in enumerate(real_symbol_by_index) if sym in group_species]
        for group_species in groups_species
    ]
    empty = [i + 1 for i, g in enumerate(groups) if not g]
    if empty:
        raise ValueError(f"--fragment-species: fragment(s) {empty} ended up with no atoms.")
    return groups


def formula_string(fdf_structure):
    """Human-readable formula (e.g. 'B16C32N16'), aggregating every species
    LABEL back to its real element (structure_io.real_element, robust to
    any fragment/ghost suffix already present) -- used for the verbose
    combined-structure/fragment reporting below.
    """
    counts = structure_io.atom_counts(fdf_structure)
    element_counts = {}
    for label, n in counts.items():
        if n <= 0:
            continue
        el = structure_io.real_element(label, fdf_structure.species_meta)
        element_counts[el] = element_counts.get(el, 0) + n
    return "".join(f"{el}{n if n > 1 else ''}" for el, n in sorted(element_counts.items()))


def species_breakdown(fdf_structure, labels):
    """Returns a sorted '<real_element> x<count> (label)' list for the given
    species `labels` of `fdf_structure` -- the per-fragment real/ghosted
    atom breakdown used for the verbose [3] FRAGMENT DEFINITION report."""
    counts = structure_io.atom_counts(fdf_structure)
    rows = []
    for label in sorted(labels):
        n = counts.get(label, 0)
        if n <= 0:
            continue
        el = structure_io.real_element(label, fdf_structure.species_meta)
        rows.append(f"{el} x{n} ({label})")
    return rows


def structure_to_view_atoms(fdf_structure, hollow_fraction=GHOST_OCCUPANCY_FRACTION):
    """Converts a (possibly ghosted) FdfStructure into a plain ASE Atoms
    object for --view, via structure_io.strip_fragment_labels (maps every
    label -- real or '_ghost' -- back to its real element by Z, preserving
    atom order) -- same conversion as before, but every atom whose
    ORIGINAL label ended in '_ghost' is additionally marked to render as a
    mostly-hollow circle in ase-gui.

    There is no public per-atom radius/fill override in ase.visualize.view()
    (it serializes Atoms to a trajectory file and opens ase-gui in a
    separate subprocess -- confirmed by reading ase/visualize/viewers.py;
    no styling hook survives that path), and the obvious alternative (the
    dummy 'X' element, Z=0) would replace the ghost's real element/size/
    color entirely with a small generic red marker. Instead, this reuses
    ase-gui's own NATIVE partial-occupancy convention (normally meant for
    disordered crystallographic sites, e.g. a fractional-occupancy CIF):
    an atom whose occupancies sum to < 1.0 is drawn as a mostly-white/empty
    circle with a small colored wedge, instead of the default fully
    solid-filled circle.

    ASE itself is inconsistent about which per-atom key this convention is
    keyed by, confirmed by reading both call sites: the INTERACTIVE Tk
    viewer (ase/gui/view.py's View.draw(), what ase.visualize.view() opens
    and what this suite's --view actually uses) reads
    `atoms.arrays['spacegroup_kinds']`, while ASE's own static PNG/EPS/POV
    writer (ase/io/utils.py's make_patch_list, used by e.g.
    `ase.io.write(path, atoms, format='png')`) reads `atoms.get_tags()`
    instead for the exact same `atoms.info['occupancy']` lookup -- so both
    are set here to render correctly regardless of which ASE code path
    ends up handling a given view. A real atom (occupancy 1.0, the default
    when its key is simply absent) renders exactly as before, fully solid
    -- so this is safe to apply uniformly to the combined structure too
    (no atom there ends in '_ghost', so every atom stays fully solid,
    unaffected).
    """
    is_ghost = [label.endswith("_ghost") for label, _ in fdf_structure.atoms]
    stripped = structure_io.strip_fragment_labels(fdf_structure)
    pmg_structure = structure_io.to_pymatgen(stripped)
    atoms = AseAtomsAdaptor.get_atoms(pmg_structure)

    if any(is_ghost):
        symbols = atoms.get_chemical_symbols()
        kinds = np.arange(len(atoms))
        atoms.arrays['spacegroup_kinds'] = kinds
        atoms.set_tags(kinds)
        atoms.info['occupancy'] = {
            str(i): {symbols[i]: (hollow_fraction if ghost else 1.0)}
            for i, ghost in enumerate(is_ghost)
        }
    return atoms


def view_fragments_animated(frames):
    """Opens ONE ase-gui window showing `frames` (a list of ASE Atoms,
    combined structure first, then each fragment) as sequential, navigable
    movie frames, with any ghost atom marked by structure_to_view_atoms
    rendering as a mostly-hollow circle.

    Deliberately bypasses core/ase_view.py's shared view_structure_interactive
    (ase.visualize.view()'s default 'ase' backend) -- confirmed by direct
    testing that this backend always pipes the structure to the ase-gui
    subprocess via ASE's own .traj (ULM binary) format, and THAT format
    silently drops any custom entry in atoms.arrays (e.g.
    'spacegroup_kinds') on the read-back side, even though it faithfully
    preserves atoms.info (e.g. 'occupancy'). Since ase-gui's own hollow
    -circle rendering (ase/gui/view.py's View.draw()) looks up
    atoms.arrays['spacegroup_kinds'] first and falls back to a normal,
    fully-solid circle on a bare KeyError, every ghost atom was silently
    rendered identically to a real one -- the exact "ghosts aren't
    differentiated" bug this works around, root-caused by writing each
    frame to a temporary CIF file instead (confirmed directly:
    'spacegroup_kinds'/'occupancy' round-trip correctly through CIF --
    unsurprising, since that's the actual format this ase-gui convention
    was designed for, crystallographic disorder) and launching 'ase gui'
    directly on that list of file paths -- ase-gui already treats multiple
    file arguments as sequential frames of one session, so no other
    change is needed for the "combined, then every fragment" movie.
    """
    with tempfile.TemporaryDirectory(prefix="stb-chargediff-view-") as tmpdir:
        paths = []
        for i, atoms in enumerate(frames):
            path = os.path.join(tmpdir, f"frame_{i:02d}.cif")
            ase_io.write(path, atoms)
            paths.append(path)
        try:
            subprocess.run([sys.executable, "-m", "ase", "gui"] + paths, check=True)
        except FileNotFoundError:
            print(color_text("[FAIL] Could not launch 'ase gui' -- is ASE installed?", 'red'))
        except subprocess.CalledProcessError as e:
            print(color_text(f"[FAIL] ase gui exited with an error: {e}", 'red'))


def write_chargediff_manifest(out_dir, fdf_structure, folder_names, suffixes, combined_folder="combined"):
    """Writes '<out_dir>/chargediff_manifest.json': the single source of
    truth stb-chargediffAnalysis (Stage 2) reads to find out, from just
    `--dir <out_dir>`, which subfolder is the combined system and which
    are the fragments -- no labels/paths need to be typed by hand. Always
    written (both --fragment-manifest/--fragment-sizes/--fragment-species
    modes), unlike core/adsorption_sites.py's own fragment_manifest.json
    (hardcoded to exactly 2 fragments: slab/adsorbate, and not written by
    this tool at all -- that one is stb-adsorb's own, only ever READ here
    via --fragment-manifest).

    `combined_folder`/`folder_names` are the literal subfolder names
    Stage 1 just wrote (e.g. 'combined' + ['fragment1', 'fragment2'], or
    'combined' + ['slab', 'adsorbate']); `suffixes` are the matching
    species-label suffixes on `fdf_structure` (the labeled, pre-ghosting
    structure) used to compute each fragment's own species/atom-count
    breakdown, purely for a human-readable record -- Stage 2 itself only
    needs 'combined_folder'/'fragment_folders' to locate each folder's own
    '*.RHO' (and the combined folder's own '*.XV'/structure.fdf for
    --cube), not this species breakdown.
    """
    counts = structure_io.atom_counts(fdf_structure)
    fragments = []
    for name, suffix in zip(folder_names, suffixes):
        species_labels = {}
        for label in fdf_structure.species:
            if label.endswith(suffix):
                info = fdf_structure.species_meta[label]
                species_labels[label] = {"id": info["id"], "Z": info["Z"], "count": counts.get(label, 0)}
        fragments.append({
            "folder": name,
            "label_suffix": suffix,
            "species_labels": species_labels,
            "n_atoms": sum(v["count"] for v in species_labels.values()),
        })
    manifest = {
        "schema": "chargediff_manifest_v2",
        "combined_folder": combined_folder,
        "fragment_folders": list(folder_names),
        "fragments": fragments,
    }
    with open(os.path.join(out_dir, CHARGEDIFF_MANIFEST_FILE), "w") as f:
        json.dump(manifest, f, indent=2)


def write_fragment_folder(out_dir, fdf_structure, calc_text, pp_path, mesh_cutoff_value,
                          spin_polarized, dipole_corrected, vdw_corrected, strip_ghost_only):
    """Writes one fragment's structure.fdf + config_extra.fdf + calc.fdf +
    copied pseudopotentials. `fdf_structure` must already be the fragment's
    REAL atoms plus every other fragment's atoms as ghosts (see
    make_ghost_variant, applied by the caller). config_extra.fdf always
    (unconditionally) forces the fixed cell, a single-point evaluation (no
    relaxation of cell OR positions -- adsorption_sites.SINGLE_POINT_BLOCK,
    same constant reused by neb.py/stackingfault.py/her_refs.py/oer_refs.py),
    the resolved MeshCutoff, and SaveRho true; the Spin/dipole/vdW blocks
    are added only when the combined system's own level of theory
    (inherited or --force-*-overridden) calls for them.

    `strip_ghost_only` controls how each present species label is resolved
    back to a real pseudopotential file under `pp_path`: True (reusing an
    stb-adsorb fragment_manifest.json, no explicit --pseudo-dir override)
    means `pp_path` is that site's own directory, which already holds
    pseudopotentials named after its own per-fragment labels (e.g.
    'C_slab.psml') -- only the literal '_ghost' suffix needs stripping,
    same convention as adsorb_bsse.py's own write_bsse_folders. False (a
    --fragment-sizes/--fragment-species split, or any case with an
    explicit --pseudo-dir/bank) means `pp_path` holds bare-element-named
    pseudopotentials (e.g. 'C.psml') -- the full real element must be
    recovered via structure_io.real_element (robust to any stack of
    suffixes).

    Returns a dict of every file actually written/attempted, for the
    caller's own verbose report: {'structure', 'config_extra', 'calc',
    'pseudo_labels'} (the last being every species label a pseudopotential
    copy was attempted for -- copy_pseudo itself warns, without raising,
    on a genuinely missing source file).
    """
    os.makedirs(out_dir, exist_ok=True)
    structure_path = os.path.join(out_dir, "structure.fdf")
    structure_io.write_fdf(fdf_structure, structure_path)

    config_extra = (
        adsorption_sites.FIXED_CELL_BLOCK
        + adsorption_sites.SINGLE_POINT_BLOCK
        + MESH_CUTOFF_BLOCK_TMPL.format(value=mesh_cutoff_value)
        + SAVE_RHO_BLOCK
    )
    if spin_polarized:
        config_extra += adsorption_sites.SPIN_POLARIZED_BLOCK
    if dipole_corrected:
        config_extra += adsorption_sites.DIPOLE_CORRECTION_BLOCK
    if vdw_corrected:
        config_extra += adsorption_sites.VDW_CORRECTION_BLOCK
    config_extra_path = os.path.join(out_dir, CONFIG_EXTRA_FILE)
    with open(config_extra_path, "w") as f:
        f.write(config_extra)

    calc_path = os.path.join(out_dir, "calc.fdf")
    with open(calc_path, "w") as f:
        f.write(structure_io.prepend_include(calc_text, CONFIG_EXTRA_FILE))

    pseudo_labels = []
    for label in fdf_structure.species:
        if strip_ghost_only:
            source_label = label[:-len("_ghost")] if label.endswith("_ghost") else label
        else:
            source_label = structure_io.real_element(label, fdf_structure.species_meta)
        copy_pseudo(pp_path, source_label, out_dir, dest_label=label)
        pseudo_labels.append(label)

    return {
        "structure": structure_path,
        "config_extra": config_extra_path,
        "calc": calc_path,
        "pseudo_labels": pseudo_labels,
    }


