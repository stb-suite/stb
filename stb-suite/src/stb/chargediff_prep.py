"""Stage 1 of the Charge Density Difference workflow: given a COMBINED
structure (a bilayer, a molecule on a slab, or any other N-fragment
system, N >= 2) and a fragment split, writes N+1 SIESTA input folders --
one 'combined/' folder with every atom real (no ghosting, the full
system as given), and one 'fragment1/', 'fragment2/', ... folder per
fragment (or 'slab/'+'adsorbate/' when reusing an stb-adsorb site's own
fragment_manifest.json). All N+1 folders share the identical cell/
MeshCutoff/level of theory, forced by this tool itself -- the combined
folder is no longer something the user has to configure/maintain
themselves in parallel, which used to be the single most dangerous
silent failure mode of this tool (a mismatched MeshCutoff between the
combined system's own calculation and the fragments').

Every fragment folder gets its own REAL atoms plus every OTHER fragment's
atoms as ghost species (see core/bsse.py::make_ghost_variant) --
unconditional, no opt-out -- so every calculation that feeds Delta rho =
rho_combined - sum(rho_fragment_i) shares the exact same basis set (same
number of atomic orbitals). Without this, a plain "real atoms only"
fragment has fewer basis functions than the combined system, and that
basis-set difference contaminates the density difference the same way it
would contaminate a counterpoise-uncorrected interaction energy. The
combined folder itself never needs ghosting -- it already has every atom.

Every one of the N+1 folders also gets, unconditionally, via
config_extra.fdf (never edited into the user's own --calc template): a
fixed cell (not relaxed), a single-point evaluation (no relaxation of
cell OR positions), the SAME explicit MeshCutoff on all of them (so every
.RHO ends up on an identical real-space grid), and SaveRho true (so
SIESTA actually writes a .RHO). See core/adsorption_sites.py's
FIXED_CELL_BLOCK/SINGLE_POINT_BLOCK/SPIN_POLARIZED_BLOCK/
DIPOLE_CORRECTION_BLOCK/VDW_CORRECTION_BLOCK for the reused blocks.
"""

